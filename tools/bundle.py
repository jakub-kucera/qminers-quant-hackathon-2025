"""Bundle a model into the one file the evaluation server accepts.

    uv run python tools/bundle.py hybrid -o dist/hybrid.py

The server instantiates `Model()` from a single file. This inlines every qqh module the model
needs, dependencies first, drops the imports between them and ends with a `Model` class that
builds the model with its preset. The result imports only the server's packages.
"""

import argparse
import ast
import importlib.util
import sys
from pathlib import Path

PACKAGE = "qqh"


def _is_package_import(node: ast.stmt) -> bool:
    if isinstance(node, ast.ImportFrom):
        return node.level > 0 or (node.module or "").split(".")[0] == PACKAGE
    if isinstance(node, ast.Import):
        return any(alias.name.split(".")[0] == PACKAGE for alias in node.names)
    return False


def _dependencies(tree: ast.Module) -> list[str]:
    found = []
    for node in tree.body:
        if isinstance(node, ast.ImportFrom) and _is_package_import(node):
            found.append(node.module)
            # from a package, a name may be a submodule (`from qqh.models import hybrid`)
            if importlib.util.find_spec(node.module).submodule_search_locations:
                for alias in node.names:
                    candidate = f"{node.module}.{alias.name}"
                    if importlib.util.find_spec(candidate) is not None:
                        found.append(candidate)
    return found


def _module_order(start: str) -> list[str]:
    """`start` and the qqh modules it imports, each after its dependencies."""
    order: list[str] = []
    seen: set[str] = set()

    def visit(name: str) -> None:
        if name in seen:
            return
        seen.add(name)
        tree = ast.parse(Path(importlib.util.find_spec(name).origin).read_text())
        for dependency in _dependencies(tree):
            visit(dependency)
        order.append(name)

    visit(start)
    return order


def _strip(source: str) -> tuple[str, list[str]]:
    """The module without its docstring, `__all__` and imports; and its outside imports."""
    tree = ast.parse(source)
    lines = source.splitlines()
    drop: set[int] = set()
    imports: list[str] = []
    for i, node in enumerate(tree.body):
        span = range(node.lineno - 1, node.end_lineno)
        is_docstring = (
            i == 0 and isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant)
        )
        is_all = isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "__all__" for t in node.targets
        )
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            if not _is_package_import(node):
                imports.append(ast.get_source_segment(source, node))
            drop.update(span)
        elif is_docstring or is_all:
            drop.update(span)
    body = "\n".join(line for n, line in enumerate(lines) if n not in drop).strip()
    return body, imports


def _top_level_names(source: str) -> set[str]:
    names = set()
    for node in ast.parse(source).body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            names.add(node.name)
        elif isinstance(node, ast.Assign):
            names.update(t.id for t in node.targets if isinstance(t, ast.Name))
    return names


def bundle(model_name: str) -> str:
    from qqh.models import MODELS

    entry = MODELS[model_name]
    cls = entry.cls
    imports: list[str] = []
    bodies: list[str] = []
    defined: dict[str, str] = {}
    for module in _module_order(cls.__module__):
        source = Path(importlib.util.find_spec(module).origin).read_text()
        body, module_imports = _strip(source)
        for name in _top_level_names(body):
            if name in defined:
                raise ValueError(f"{name} is defined in both {defined[name]} and {module}")
            defined[name] = module
        imports.extend(i for i in module_imports if i not in imports)
        if body:
            bodies.append(f"# --- {module} ---\n\n{body}")

    if entry.preset:
        tail = (
            f"class Model({cls.__name__}):\n"
            f"    def __init__(self):\n"
            f"        super().__init__(**{entry.preset})\n"
        )
    else:
        tail = f"class Model({cls.__name__}):\n    pass\n"
    header = (
        f'"""{model_name}: {entry.summary}.\n\n'
        f"Generated by tools/bundle.py from {cls.__module__}; edit the package, not this file.\n"
        '"""'
    )
    parts = [header, "\n".join(sorted(imports, key=_import_sort_key)), *bodies, tail]
    return "\n\n\n".join(parts)


def _import_sort_key(statement: str) -> tuple[int, str, str]:
    module = statement.split()[1]
    stdlib = module.split(".")[0] in sys.stdlib_module_names
    return (0 if stdlib else 1, module, statement)


def main() -> None:
    from qqh.models import MODELS

    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("model", choices=list(MODELS))
    parser.add_argument("-o", "--output", type=Path)
    args = parser.parse_args()
    source = bundle(args.model)
    if args.output is None:
        print(source)
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(source)


if __name__ == "__main__":
    main()
